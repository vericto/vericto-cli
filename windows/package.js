// Windows packaging for a release, from its archives' published SHA-256
// (sha256.sum and the per-archive .sha256, as cargo-dist writes them):
//
//   installer  vericto-cli-installer.ps1, rendered from windows/installer.ps1
//              with every Windows archive pinned by its SHA-256;
//   scoop      vericto.json, the manifest for the Scoop bucket
//              (github.com/vericto/scoop-bucket);
//   winget     the three manifests of Vericto.VerictoCLI for
//              microsoft/winget-pkgs (version, installer, defaultLocale).
//
// Every output points at the release's GitHub download URLs and carries the
// archives' SHA-256; it fails, and so stops the release, when an archive has
// no checksum or the version is not one.
//
// usage: node windows/package.js <installer|scoop|winget> <artifacts dir> <version> <output>
// (`installer` and `scoop` write a file, `winget` a directory.)

"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { readChecksums } = require("../npm-installer/harden-package.js");

// The cargo-dist version windows/installer.ps1 was derived from. Rendering
// refuses any other, so an upgrade cannot ship a stale installer unnoticed.
const UPSTREAM_CARGO_DIST_VERSION = "0.32.0";

const REPO = "vericto/vericto-cli";
const TEMPLATE = path.join(__dirname, "installer.ps1");
const DIST_CONFIG = path.join(__dirname, "..", "dist-workspace.toml");

// The Windows archives of a release, by the architecture names of each channel.
const ARCHIVES = [
  { target: "x86_64-pc-windows-msvc", scoop: "64bit", winget: "x64" },
  { target: "aarch64-pc-windows-msvc", scoop: "arm64", winget: "arm64" },
].map((a) => ({ ...a, name: `vericto-cli-${a.target}.zip` }));

const DESCRIPTION = "Validate SQL against your Vericto workspace's security rules before it runs";
const LICENSE = "FSL-1.1-ALv2";
const LICENSE_URL = `https://github.com/${REPO}/blob/main/LICENSE`;

function checkVersion(version) {
  if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version || "")) {
    throw new Error(`not a release version: ${JSON.stringify(version)}`);
  }
}

function downloadUrl(version, name) {
  return `https://github.com/${REPO}/releases/download/v${version}/${name}`;
}

function sha256Of(sums, name) {
  const sum = sums.get(name);
  if (!sum) throw new Error(`no published SHA-256 for ${name}`);
  return sum;
}

// The cargo-dist version dist-workspace.toml builds the release with.
function configuredCargoDistVersion(configText) {
  const m = configText.match(/^cargo-dist-version\s*=\s*"([^"]+)"/m);
  if (!m) throw new Error("dist-workspace.toml sets no cargo-dist-version");
  return m[1];
}

function renderInstaller(template, version, sums, distVersion = UPSTREAM_CARGO_DIST_VERSION) {
  checkVersion(version);
  if (distVersion !== UPSTREAM_CARGO_DIST_VERSION) {
    throw new Error(
      `the release uses cargo-dist ${distVersion}, windows/installer.ps1 is derived from ` +
        `${UPSTREAM_CARGO_DIST_VERSION}: port the new upstream installer and update UPSTREAM_CARGO_DIST_VERSION`,
    );
  }
  const out = template
    .replaceAll("@VERSION@", version)
    .replace(/@SHA256:([^@\s]+)@/g, (_, name) => sha256Of(sums, name));
  const left = out.match(/@(VERSION|SHA256:[^@\s]+)@/);
  if (left) throw new Error(`placeholder left in the installer: ${left[0]}`);
  // Windows PowerShell 5.1 reads a script without a BOM in the ANSI code page:
  // keep it ASCII so it reads the same everywhere.
  if (/[^\x00-\x7f]/.test(out)) throw new Error("the installer must be ASCII");
  return out;
}

function scoopManifest(version, sums) {
  checkVersion(version);
  const architecture = {};
  const autoupdate = {};
  for (const a of ARCHIVES) {
    architecture[a.scoop] = { url: downloadUrl(version, a.name), hash: sha256Of(sums, a.name) };
    autoupdate[a.scoop] = {
      url: `https://github.com/${REPO}/releases/download/v$version/${a.name}`,
      hash: { url: "$url.sha256" },
    };
  }
  return {
    version,
    description: DESCRIPTION,
    homepage: "https://vericto.com",
    license: { identifier: LICENSE, url: LICENSE_URL },
    architecture,
    bin: "vericto.exe",
    checkver: { github: `https://github.com/${REPO}` },
    autoupdate: { architecture: autoupdate },
  };
}

const WINGET_ID = "Vericto.VerictoCLI";
const WINGET_SCHEMA = "1.10.0";

// YAML scalars written here are plain ASCII without YAML syntax, except the
// description, which is quoted.
function wingetManifests(version, sums) {
  checkVersion(version);
  const head = (type) =>
    `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.${WINGET_SCHEMA}.schema.json\n` +
    `# Generated by windows/package.js for ${REPO} v${version}.\n\n` +
    `PackageIdentifier: ${WINGET_ID}\nPackageVersion: ${version}\n`;
  const tail = (type) => `ManifestType: ${type}\nManifestVersion: ${WINGET_SCHEMA}\n`;
  const installers = ARCHIVES.map(
    (a) =>
      `- Architecture: ${a.winget}\n` +
      `  InstallerUrl: ${downloadUrl(version, a.name)}\n` +
      `  InstallerSha256: ${sha256Of(sums, a.name).toUpperCase()}\n`,
  ).join("");
  return {
    [`${WINGET_ID}.yaml`]: head("version") + "DefaultLocale: en-US\n" + tail("version"),
    [`${WINGET_ID}.installer.yaml`]:
      head("installer") +
      "InstallerType: zip\n" +
      "NestedInstallerType: portable\n" +
      "NestedInstallerFiles:\n" +
      "- RelativeFilePath: vericto.exe\n" +
      "  PortableCommandAlias: vericto\n" +
      "Commands:\n- vericto\n" +
      "Installers:\n" +
      installers +
      tail("installer"),
    [`${WINGET_ID}.locale.en-US.yaml`]:
      head("defaultLocale") +
      "PackageLocale: en-US\n" +
      "Publisher: Vericto S.A.S.\n" +
      "PublisherUrl: https://vericto.com\n" +
      `PublisherSupportUrl: https://github.com/${REPO}/issues\n` +
      "PackageName: Vericto CLI\n" +
      `PackageUrl: https://github.com/${REPO}\n` +
      `License: ${LICENSE}\n` +
      `LicenseUrl: ${LICENSE_URL}\n` +
      `ShortDescription: ${JSON.stringify(DESCRIPTION)}\n` +
      "Moniker: vericto\n" +
      "Tags:\n- sql\n- security\n- ci\n- database\n- cli\n" +
      `ReleaseNotesUrl: https://github.com/${REPO}/releases/tag/v${version}\n` +
      tail("defaultLocale"),
  };
}

module.exports = {
  ARCHIVES,
  UPSTREAM_CARGO_DIST_VERSION,
  configuredCargoDistVersion,
  renderInstaller,
  scoopManifest,
  wingetManifests,
};

if (require.main === module) {
  const [what, artifactsDir, version, output] = process.argv.slice(2);
  if (!["installer", "scoop", "winget"].includes(what) || !artifactsDir || !version || !output) {
    console.error("usage: package.js <installer|scoop|winget> <artifacts dir> <version> <output>");
    process.exit(2);
  }
  try {
    const sums = readChecksums(artifactsDir);
    if (what === "installer") {
      const dist = configuredCargoDistVersion(fs.readFileSync(DIST_CONFIG, "utf8"));
      fs.writeFileSync(output, renderInstaller(fs.readFileSync(TEMPLATE, "utf8"), version, sums, dist));
    } else if (what === "scoop") {
      fs.writeFileSync(output, JSON.stringify(scoopManifest(version, sums), null, 4) + "\n");
    } else {
      fs.mkdirSync(output, { recursive: true });
      for (const [name, text] of Object.entries(wingetManifests(version, sums))) {
        fs.writeFileSync(path.join(output, name), text);
      }
    }
    console.log(`wrote ${what} for vericto-cli ${version} to ${output}`);
  } catch (e) {
    console.error(`package.js: ${e.message}`);
    process.exit(1);
  }
}
